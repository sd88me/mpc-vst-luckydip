#!/usr/bin/env python3
"""vst/params.json -> src/params_gen.h: the parameter table of the native front end (src/LuckyDipPlugin.cpp).

The VST order is the released 0.9.2 wrapper build's: the 161 keys of vst/params.json, checked against vst/params.lock (the
0.9.2 build had no hidden popup flags, so nothing else sits between them). New parameters are appended after them. Append only.

Kinds (flags):
  kText    a readout (display "string", range 0..0 in 1.x): the value is a change counter, the text is the engine's
  kToggle  a toggle with a label (display "string", range 0..1: pad locks, category keys): value = the engine's "<key>_on"
  kMomentary  a verb: fires on 0 -> 1, then drops back to 0; kStep nudges another param (PAD < >)
  kChoice  an option list; kPolled: a value the engine may change by itself (read back by the worker)
"""
import json, os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..")
P = json.load(open(os.path.join(ROOT, "vst", "params.json")))["params"]
LOCK = [l.strip() for l in open(os.path.join(ROOT, "vst", "params.lock")) if l.strip()]

keys = [p["key"] for p in P]
if keys != LOCK:
    raise SystemExit("vst/params.json no longer matches vst/params.lock: the order is frozen (append only)")
idx = {k: i for i, k in enumerate(keys)}

FL = dict(kMomentary=1, kText=2, kToggle=4, kChoice=8, kStep=16, kNoAuto=32, kPolled=64, kLocal=128)
out = ["/* generated by tools/gen_params.py from vst/params.json: do not edit. One row per parameter, in the frozen VST order. */",
       "#pragma once",
       "enum { %s };" % ", ".join("%s = %d" % kv for kv in FL.items()),
       "struct PSpec { const char *key, *name; float min, max, def; int flags; const char *const *choices; int nchoices; int stepTarget; float stepDelta; };",
       ""]
rows = []


def F(v):
    t = "%g" % v
    return t + ("f" if ("." in t or "e" in t) else ".0f")


def row(key, name, lo, hi, d, fl, ch="nullptr", n=0, st=-1, sd=0.0):
    rows.append("    {%s, %s, %s, %s, %s, %d, %s, %d, %d, %s}," % (json.dumps(key), json.dumps(name), F(lo), F(hi), F(d), fl, ch, n, st, F(sd)))


for i, p in enumerate(P):
    k = p["key"]
    fl, ch, n, st, sd = 0, "nullptr", 0, -1, 0.0
    if "options" in p:
        fl |= FL["kChoice"] | FL["kPolled"]
        opts = p["options"]
        out.append("static const char *const ch_%d[] = {%s};" % (i, ", ".join(json.dumps(o) for o in opts)))
        ch, n = "ch_%d" % i, len(opts)
        lo, hi, d = 0, len(opts) - 1, p.get("default", 0)
    elif p.get("momentary"):
        fl |= FL["kMomentary"] | FL["kNoAuto"]
        lo, hi, d = 0, 1, 0
        if p.get("step_of"):
            fl |= FL["kStep"]
            st, sd = idx[p["step_of"]], p.get("step_delta", 1)
    elif p.get("display") == "string":
        if p.get("max", 0) > 0:
            fl |= FL["kToggle"] | FL["kPolled"]
            lo, hi, d = 0, 1, p.get("default", 0)
        else:
            fl |= FL["kText"] | FL["kNoAuto"]
            lo, hi, d = 0, 1023, 0
    else:
        fl |= FL["kPolled"]
        lo, hi, d = p["min"], p["max"], p.get("default", p["min"])
    row(k, p["name"], lo, hi, d, fl, ch, n, st, sd)

# ---- appended after the frozen 161 (none yet) ----

out += ["", "static const PSpec g_pspecs[] = {"] + rows + ["};",
        "static const int kNumParams = %d;" % len(rows),
        "static const int kNumEngineParams = %d;   // 0 .. this - 1 are the engine's keys" % len(P), ""]
open(os.path.join(ROOT, "src", "params_gen.h"), "w").write("\n".join(out))
print("src/params_gen.h: %d params (%d engine)" % (len(rows), len(P)))
